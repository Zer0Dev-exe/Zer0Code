export function relativePath(file, workspace) {
  const f = String(file || '');
  const w = String(workspace || '').replace(/[\\/]+$/, '');
  return w && f.startsWith(w + '/') ? f.slice(w.length + 1) : f;
}

const MONOGRAM_COLORS = ['#e5484d', '#f76b15', '#ca8a04', '#30a46c', '#0d9488', '#0091ff', '#6e56cf', '#d6409f'];
export function monogram(name, cls = '') {
  const label = String(name || '?').trim();
  let hash = 0;
  for (const ch of label) hash = (hash * 31 + ch.charCodeAt(0)) >>> 0;
  return h('span', { class: `monogram ${cls}`.trim(), style: { background: MONOGRAM_COLORS[hash % MONOGRAM_COLORS.length] } }, label[0]?.toUpperCase() || '?');
}

