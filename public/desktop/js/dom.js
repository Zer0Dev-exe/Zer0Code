let openPopover = null;

export function closePopover() {
  if (!openPopover) return;
  openPopover.el.remove();
  document.removeEventListener('mousedown', openPopover.onDown, true);
  document.removeEventListener('keydown', openPopover.onKey, true);
  openPopover.onClose?.();
  openPopover = null;
}

/** Abre `content` (Node) junto a `anchor`. side: 'bottom' | 'top'; align: 'start' | 'end' */
export function showPopover(anchor, content, { side = 'bottom', align = 'start', className = '', onClose } = {}) {
  closePopover();
  const el = h('div', { class: `popover ${className}`.trim() }, content);
  document.getElementById('popovers').append(el);
  const place = () => {
    const a = anchor.getBoundingClientRect();
    const r = el.getBoundingClientRect();
    let left = align === 'end' ? a.right - r.width : a.left;
    left = Math.max(8, Math.min(left, innerWidth - r.width - 8));
    let top = side === 'top' ? a.top - r.height - 6 : a.bottom + 6;
    if (top + r.height > innerHeight - 8) top = Math.max(8, a.top - r.height - 6);
    if (top < 8) top = 8;
    el.style.left = `${left}px`;
    el.style.top = `${top}px`;
  };
  place();
  const onDown = (e) => { if (!el.contains(e.target) && !anchor.contains(e.target)) closePopover(); };
  const onKey = (e) => { if (e.key === 'Escape') { e.stopPropagation(); closePopover(); } };
  document.addEventListener('mousedown', onDown, true);
  document.addEventListener('keydown', onKey, true);
  openPopover = { el, onDown, onKey, onClose };
  return { el, place };
}

/** Fila de menú */
export function menuItem({ label, hint, icon: ic, onClick, danger = false, selected = false, disabled = false }) {
  return h('button', {
    class: `menu-item${danger ? ' danger' : ''}${selected ? ' selected' : ''}`,
    type: 'button',
    disabled,
    onclick: (e) => { e.stopPropagation(); onClick?.(e); }
  }, ic ? icon(ic) : null, h('span', { class: 'menu-label' }, label), hint ? h('span', { class: 'menu-hint' }, hint) : null, selected ? icon('check', 'menu-check') : null);
}

